export function resolveLanguage(preference: string): SupportedLanguage {
  if (preference !== 'auto') {
    if (preference in DICTIONARIES) return preference as SupportedLanguage;
    if (preference.toLowerCase().startsWith('pt')) return 'pt-BR';
  }
  const tags = typeof navigator !== 'undefined' ? [...(navigator.languages ?? []), navigator.language] : [];
  for (const tag of tags) {
    const lower = String(tag ?? '').toLowerCase();
    if (lower.startsWith('pt')) return 'pt-BR';
    const base = lower.split('-')[0];
    if (base in DICTIONARIES) return base as SupportedLanguage;
  }
  return 'en';
}

export function localeForLanguage(lang: SupportedLanguage): string {
  switch (lang) {
    case 'pt-BR':
      return 'pt-BR';
    case 'fr':
      return 'fr-FR';
    case 'es':
      return 'es-ES';
    case 'de':
      return 'de-DE';
    default:
      return 'en-GB';
  }
}

export function translate(lang: SupportedLanguage, key: string, ...args: Array<string | number>): string {
  const template = DICTIONARIES[lang]?.[key] ?? DICTIONARIES.en[key] ?? key;
  return args.reduce<string>((acc, value, index) => acc.replace(`{${index}}`, String(value)), template);
}

export function formatBytes(bytes: number, perSecond = false): string {
  const units = ['B', 'KB', 'MB', 'GB', 'TB'];
  let value = Math.max(0, bytes);
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit += 1;
  }
  const text = `${value.toFixed(value >= 100 || unit === 0 ? 0 : 1)} ${units[unit]}`;
  return perSecond ? `${text}/s` : text;
}

export function formatGiB(bytes: number): string {
  return (bytes / 1024 ** 3).toFixed(1);
}

export function formatUptime(lang: SupportedLanguage, ms: number): string {
  const minutes = Math.floor(Math.max(0, ms) / 60_000);
  const days = Math.floor(minutes / 1440);
  const hours = Math.floor((minutes % 1440) / 60);
  const rest = minutes % 60;
  if (days > 0) return translate(lang, 'uptime_days', days, hours);
  if (hours > 0) return translate(lang, 'uptime_hours', hours, String(rest).padStart(2, '0'));
  return translate(lang, 'uptime_mins', rest);
}
